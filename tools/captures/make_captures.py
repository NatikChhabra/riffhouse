#!/usr/bin/env python3
"""Builds src/dsp/FactoryCaptures.h from Neural Amp Modeler captures.

The captures come from the community collection at github.com/pelennor2170/NAM_models
(GNU GPL v3, see tools/captures/COPYING-NAM_models.txt). Each capture's config goes in as a
short JSON string and its weights as a float array, so no compiler meets a huge string.

  python3 tools/captures/make_captures.py <folder with the .nam files>
"""
import json, os, sys

# amp voicing it stands in for, file name in the collection, who made it
CAPTURES = [
    ("Modern High Gain", "Helga B 5150 BlockLetter - NoBoost.nam", "Helga Behrens"),
    ("Tight Metal",      "Helga B 6505+ Red ch - NoBoost.nam",     "Helga Behrens"),
    ("Brit 81",          "Tim R JCM2000 L2 G8.nam",                "Tim Robertson"),
    ("Redline Lead",     "Phillipe P JVM-OD1-GR-NoDrive-ESR0,015.nam", "Phillipe Priss"),
]

def lit(x):
    t = format(float(x), ".9g")
    if not any(c in t for c in ".en"): t += ".0"
    return t + "f"

def main(src):
    out = ["// Generated by tools/captures/make_captures.py. Do not edit.",
           "// Neural Amp Modeler captures from github.com/pelennor2170/NAM_models, GNU GPL v3.",
           "#pragma once", "", "namespace rh::factory_captures", "{"]
    entries = []
    for i, (voicing, fname, author) in enumerate(CAPTURES):
        d = json.load(open(os.path.join(src, fname)))
        w = d.pop("weights")
        cfg = json.dumps(d, separators=(",", ":"))
        assert len(cfg) < 15000, (fname, len(cfg))
        name = os.path.splitext(fname)[0]
        out.append(f"inline constexpr float weights{i}[] = {{")
        for k in range(0, len(w), 8):
            out.append("    " + ", ".join(lit(x) for x in w[k:k + 8]) + ",")
        out.append("};")
        esc = cfg.replace("\\", "\\\\").replace('"', '\\"')
        entries.append(f'    {{ "{voicing}", "{name}", "{author}", "{esc}", weights{i}, sizeof (weights{i}) / sizeof (float) }},')
    out += ["", "struct Capture { const char* voicing; const char* name; const char* author; const char* config; const float* weights; unsigned long count; };",
            "inline constexpr Capture all[] = {"] + entries + ["};",
            "inline constexpr int count = (int) (sizeof (all) / sizeof (all[0]));", "} // namespace rh::factory_captures", ""]
    open(os.path.join(os.path.dirname(__file__), "..", "..", "src", "dsp", "FactoryCaptures.h"), "w").write("\n".join(out))

if __name__ == "__main__":
    main(sys.argv[1])
