#!/usr/bin/env python3
"""Builds src/dsp/DerivedCabIrs.h: a fourth real-cab voicing taken from the magnitude response of
the mic'd 4x12 in Phillipe Priss's JVM OD2 capture pair (cab / no cab; NAM_models, GPL-3), measured
by tools/cabs/derive_jvm_cab_response.py and stored in jvm_cab_response.csv.

The response is smoothed to a third of an octave, extended (12 dB/oct below 63 Hz, 30 dB/oct above
8 kHz, where the capture runs out of signal and the Jester cabs fall at a similar rate), turned into
a minimum-phase IR (cepstrum), cut to 4096 samples at 48 kHz and stored in 16-bit steps like the
others. Two IRs make the mic knob work: the response as measured (bright) and the same with the
bright-to-dark change the Jester recordings show (about 3 dB less from 2.5 to 6 kHz).

    python3 tools/cabs/make_derived_cab.py
"""
import os, numpy as np
HERE = os.path.dirname(__file__)
SR, N, FADE, NF = 48000, 4096, 1024, 1 << 15

def curve():
    pts = np.loadtxt(os.path.join(HERE, "jvm_cab_response.csv"), delimiter=",", skiprows=3)
    lf, db = np.log2(pts[:, 0]), pts[:, 1]
    k = np.exp(-0.5 * (np.arange(-3, 4) * (1 / 6) / (1 / 6)) ** 2); k /= k.sum()   # about a third of an octave
    sm = np.convolve(np.pad(db, 3, mode="edge"), k, mode="valid")
    f = np.fft.rfftfreq(NF, 1 / SR); out = np.zeros(len(f)); lo, hi = pts[0, 0], pts[-1, 0]
    for i, hz in enumerate(f):
        if hz <= 0: out[i] = sm[0] - 40
        elif hz < lo: out[i] = sm[0] - 12 * np.log2(lo / hz)
        elif hz > hi: out[i] = sm[-1] - 30 * np.log2(hz / hi)
        else: out[i] = np.interp(np.log2(hz), lf, sm)
    return f, out

def minphase(mag_db):
    mag = 10 ** (mag_db / 20); n = NF
    c = np.fft.irfft(np.log(mag + 1e-9), n)
    w = np.zeros(n); w[0] = 1; w[1:n // 2] = 2; w[n // 2] = 1
    h = np.fft.irfft(np.exp(np.fft.rfft(c * w)), n)
    h = h[:N].copy(); h[N - FADE:] *= 0.5 * (1 + np.cos(np.pi * np.arange(FADE) / FADE))
    return h

def main():
    f, bright = curve()
    shelf = -3.0 * np.clip((np.log2(np.maximum(f, 1) / 1800.0)) / 0.5, 0, 1) * np.clip(1 - np.log2(np.maximum(f, 1) / 6000.0) / 0.5, 0, 1)
    dark = bright + shelf
    irs = [minphase(bright), minphase(dark)]
    out = ["// Generated by tools/cabs/make_derived_cab.py: do not edit by hand.",
           "// A fourth real-cab voicing: the magnitude response of the mic'd 4x12 in Phillipe Priss's JVM OD2",
           "// NAM capture pair (cab / no cab), from NAM_models (GPL-3), as a minimum-phase IR. 48 kHz, 4096",
           "// samples, 16-bit steps of the IR's own peak. Bright placement first, then the darker one.",
           "#pragma once", "#include \"RealCabIrs.h\"", "", "namespace rh::realcabs", "{"]
    for i, x in enumerate(irs):
        q = np.round(x / np.abs(x).max() * 32767).astype(int)
        out.append("inline constexpr std::int16_t irD%d[kLength] = {" % (i + 1))
        for j in range(0, N, 24): out.append("    " + ", ".join(str(v) for v in q[j:j + 24]) + ",")
        out.append("};")
    out += ["inline constexpr Family kDerivedFamilies[] = {", '    { "4x12 Real Presence", 2, { irD1, irD2 } },', "};",
            "constexpr int kNumDerived = 1;", "} // namespace rh::realcabs", ""]
    open(os.path.join(HERE, "..", "..", "src", "dsp", "DerivedCabIrs.h"), "w").write("\n".join(out))
    for n, x in zip(("bright", "dark"), irs):
        X = np.abs(np.fft.rfft(x, NF)); fr = np.fft.rfftfreq(NF, 1 / SR)
        print(n, {c: round(float(20 * np.log10(X[np.argmin(abs(fr - c))] + 1e-12)), 1) for c in (100, 250, 1000, 3000, 5000, 8000, 10000)})
main()
