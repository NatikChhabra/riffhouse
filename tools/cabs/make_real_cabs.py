#!/usr/bin/env python3
"""Builds src/dsp/RealCabIrs.h from Jester's Brutal Pack, real 4x12 cabinet impulse responses
by Jester Dyne Productions, dedicated to the public domain (CC0 1.0, see the pack's handbook).

    python3 tools/cabs/make_real_cabs.py <folder of the pack's 48 kHz wav files>

Each IR is cut to its first 4096 samples (85 ms at 48 kHz; what is left after that is more than
25 dB down), faded over the last 1024 and stored as 16-bit steps of its own peak. The IRs are
grouped by the speaker in the cab and ordered brightest first (most level from 2.5 to 5 kHz
against 250 Hz to 2 kHz), so the cab's mic knob sweeps from the bright spot to the dark one.
"""
import sys, os, glob
import numpy as np, soundfile as sf

FAMILIES = [  # (name in the app, pack numbers of the IRs with one speaker type each)
    ("4x12 Real Classic", [1, 9, 12, 14]),   # one British-voiced speaker, three close mics
    ("4x12 Real Heavy",   [2, 10, 13, 15]),  # a heavier, darker American-voiced speaker
    ("4x12 Real Tight",   [3, 11]),          # a tight modern speaker
]
N, FADE = 4096, 1024

def brightness(ir, sr=48000):
    """Power from 2.5 to 5 kHz (1/24-octave points) against the mean level at 250, 500, 1000 and
    2000 Hz: how the app sets each cab's loudness, and how its tests judge the mic knob."""
    t = np.arange(len(ir)) / sr
    db = lambda f: 10 * np.log10(abs(np.sum(ir * np.exp(-2j * np.pi * f * t))) ** 2 + 1e-30)
    upper = 2500.0 * 2.0 ** (np.arange(25) / 24.0)
    p = np.mean([10 ** (db(f) / 10) for f in upper])
    return 10 * np.log10(p) - np.mean([db(f) for f in (250, 500, 1000, 2000)])

def main(folder):
    files = {int(os.path.basename(p).split("_")[0]): p for p in glob.glob(os.path.join(folder, "*.wav"))}
    out = ["// Generated by tools/cabs/make_real_cabs.py: do not edit by hand.",
           "// Real 4x12 cabinet impulse responses from Jester's Brutal Pack by Jester Dyne Productions",
           "// (jester-dyne-productions.com), dedicated to the public domain under CC0 1.0. 48 kHz,",
           "// 4096 samples each, in 16-bit steps of the IR's own peak.",
           "#pragma once", "#include <cstdint>", "", "namespace rh::realcabs", "{",
           "constexpr int kLength = %d;" % N, "constexpr double kRate = 48000.0;", ""]
    fams = []
    for name, nums in FAMILIES:
        irs = []
        for n in nums:
            x, sr = sf.read(files[n]); assert sr == 48000, files[n]
            x = x[:, 0] if x.ndim > 1 else x
            x = x[:N].copy(); x[N - FADE:] *= 0.5 * (1 + np.cos(np.pi * np.arange(FADE) / FADE))
            irs.append((brightness(x), n, x))
        irs.sort(key=lambda t: -t[0])
        fams.append((name, irs))
        for b, n, x in irs:
            peak = np.abs(x).max(); q = np.round(x / peak * 32767).astype(int)
            out.append("// pack IR %d, %+.1f dB at 2.5-5 kHz" % (n, b))
            out.append("inline constexpr std::int16_t ir%d[kLength] = {" % n)
            for i in range(0, N, 24): out.append("    " + ", ".join(str(v) for v in q[i:i + 24]) + ",")
            out.append("};")
    out.append("")
    out.append("struct Family { const char* name; int count; const std::int16_t* irs[4]; };")
    out.append("inline constexpr Family kFamilies[] = {")
    for name, irs in fams:
        ptrs = ", ".join("ir%d" % n for _, n, _ in irs)
        out.append('    { "%s", %d, { %s } },' % (name, len(irs), ptrs))
    out += ["};", "constexpr int kNumFamilies = %d;" % len(fams), "} // namespace rh::realcabs", ""]
    dst = os.path.join(os.path.dirname(__file__), "..", "..", "src", "dsp", "RealCabIrs.h")
    open(dst, "w").write("\n".join(out))
    for name, irs in fams: print(name, ["%d (%+.1f)" % (n, b) for b, n, _ in irs])

if __name__ == "__main__":
    main(sys.argv[1])
